-- "921$c") — pour transférer une valeur du XML directement dans sa cellule,
-- sans renommage. Liste exacte : scripts/lib/marc-columns.mjs
-- (NOTICE_LITERAL_FIELDS / ITEM_LITERAL_FIELDS), source unique partagée avec
-- scripts/db-migrate-reserve.mjs — voir ce module pour le détail des deux
-- exceptions volontaires (995$* écarté, 921$c ajouté malgré sa rareté).
--
-- Un champ plus rare que ce seuil reste capturé sans perte dans la colonne
-- `raw` (jsonb, flatten() complet) — rien n'est jamais perdu, ces colonnes ne
-- sont qu'un accès direct en SQL aux champs les plus utiles.
--
-- Remplace les colonnes "notices" renommées qui n'étaient utiles qu'à la
-- source reserve_marc (titre_complement, editeur_lieu, collation_desc,
-- dimensions, langue, pays, notes) et la table de jonction
-- contributeurs/notice_contributeurs (auteurs 700/701/702) : plus rien n'en
-- dépend en aval (export-inventaire.mjs reconstruit déjà data/inventaire.json
-- depuis la colonne `raw`, jamais depuis ces colonnes/tables), et les
-- colonnes littérales "700$a"/"700$b"/… les remplacent avec plus de
-- fidélité (auteurs multiples joints par §, comme dans data/inventaire.json).
-- Les colonnes partagées avec les sources bib_xml/excel_import (titre,
-- editeur_nom, editeur_date, isbn, issn, auteur_principal, cote_1/2/3,
-- piege_*, etat_*, section_*, bibliotheque_*) restent inchangées.
--
-- Idempotent (ADD/DROP COLUMN IF [NOT] EXISTS, DROP TABLE IF EXISTS), comme
-- 0001_init.sql/0002_livres_spolies.sql.

