-- ── Journal des rafraîchissements (refresh) ─────────────────────────────────
-- Une ligne par exécution de scripts/db-migrate-reserve.mjs (et, même forme,
-- réutilisable par les autres scripts db-migrate-*.mjs). `admin.html` affiche
-- la ligne la plus récente par `source` — la date à indiquer côté Syracuse
-- pour n'exporter que les notices modifiées depuis (`started_at`, capturé
-- avant la moindre lecture du XML : un léger recouvrement avec la prochaine
-- fenêtre d'export est sans risque — une notice réexportée deux fois se
-- réapplique à l'identique — alors qu'une date prise après coup risquerait
-- de sauter des modifications survenues pendant le traitement).
CREATE TABLE IF NOT EXISTS sync_runs (
  id                  bigserial PRIMARY KEY,
  source              text NOT NULL,   -- 'reserve_marc', 'bib_xml', …
  started_at          timestamptz NOT NULL,
  finished_at         timestamptz,
  notices_upserted    integer,
  exemplaires_upserted integer,
  status              text NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'error')),
  error_message       text
);
CREATE INDEX IF NOT EXISTS idx_sync_runs_source_started ON sync_runs (source, started_at DESC);
